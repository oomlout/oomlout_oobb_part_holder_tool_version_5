def main(**kwargs):
    selected = kwargs.get("filter", "")
    profiles = kwargs.get("profiles", get_profiles())
    options = kwargs.get("options", get_options())
    assemblies = kwargs.get("assemblies", get_tool_assemblies())
    geometry_defaults = {
        "oobb_type": "holder_tool",
        "run_scad": True,
        "run_solidcraft": False,
        "count": 1,
        "spacing_mm": 15,
        "offset_mm": [0, 0, 0],
        "layered": False,
        "pitch_mm": 15,
        "corner_radius_mm": 5,
        "edge_reduction_mm": 1,
    }
    drawing_defaults = {
        "svg_name": "holder_sections",
        "show_underside": False,
        "near_face_fraction": 0.08,
        "cross_section_y_fraction": 0.82,
    }
    records = []
    identifiers = set()
    for option in options:
        width = option["width"]
        height = option["height"]
        depth = option["depth"]
        size = f"{width}x{height}x{depth:g}".replace(".", "d")
        taxonomy = [
            "oobb", "part", "holder_tool",
            option["tool_type"], option["model"], option["layout"], size,
        ]
        part_id = "_".join(taxonomy)
        if part_id in identifiers:
            raise ValueError(f"Duplicate tool holder {part_id}")
        identifiers.add(part_id)
        if selected and selected not in part_id:
            continue
        geometry = deepcopy(geometry_defaults)
        for field in geometry_defaults:
            if field in option:
                geometry[field] = deepcopy(option[field])
        geometry.update({
            "width": width,
            "height": height,
            "depth": depth,
            "body_style": option["body_style"],
            "profile": deepcopy(profiles[option["profile"]]),
        })
        for field in ("bottom_m6_clearance_mm", "row_count", "row_pitch_mm"):
            if field in option:
                geometry[field] = option[field]
        drawing = deepcopy(drawing_defaults)
        for field in drawing_defaults:
            if field in option:
                drawing[field] = option[field]
        record = {
            **option,
            "oobb_type": geometry["oobb_type"],
            "oobb_details": geometry,
            "svg_details": drawing,
            "construction": get_construction(option=option),
        }
        recipe = assemblies.get(part_id, assemblies.get(option["model"], {}))
        if recipe and option["layout"] == recipe.get("layout", "1_place"):
            tool = deepcopy(recipe)
            record["assembly_details"] = {
                **tool,
                "steps": get_loading_steps(tool=tool),
                "style": get_book_style(),
            }
        for level, segment in enumerate(taxonomy, start=1):
            record[f"taxonomy_{level}"] = segment
        records.append(record)
    if not records:
        raise ValueError(f"No holder matches {selected!r}")
    with chdir(ROOT):
        write_extras(records)
    write_file(ROOT / "parts_source/catalogue.txt", "\n".join(sorted(identifiers)) + "\n")


