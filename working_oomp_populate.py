def get_loading_steps(**kwargs):
    tool = kwargs["tool"]
    quantity = len(tool.get("instance_offsets_mm", tool.get("instance_x_mm", [0])))
    if "custom_steps" in tool:
        return deepcopy(tool["custom_steps"])
    if tool.get("single_piece", False):
        return [
            {
                "key": "step_01",
                "action": "Place the printed block upright with all pocket openings facing up.",
                "add": ["holder"],
                "upper_lift_mm": 0,
                "withdraw_mm": 0,
            },
            {
                "key": "step_02",
                "action": tool["alignment"],
                "add": ["tool"] * quantity,
                "upper_lift_mm": 0,
                "withdraw_mm": 70,
            },
            {
                "key": "step_03",
                "action": "Lower the bits into the pockets. " + tool["check"],
                "add": [],
                "upper_lift_mm": 0,
                "withdraw_mm": 0,
            },
        ]
    return [
        {
            "key": "step_01",
            "action": "Orient the rear half as it sits on the wall, with the pocket facing you and the opening at the top.",
            "add": ["holder"],
            "upper_lift_mm": 0,
            "withdraw_mm": 0,
        },
        {
            "key": "step_02",
            "action": "Face the front half toward the rear pocket. Align the mounting holes and both top openings.",
            "add": ["holder"],
            "upper_lift_mm": 36,
            "withdraw_mm": 0,
        },
        {
            "key": "step_03",
            "action": "Bring the halves together until their rims meet. " + tool["alignment"],
            "add": ["tool"] * quantity + [extra["key"] for extra in tool.get("additional_tools", [])],
            "upper_lift_mm": 0,
            "withdraw_mm": 70,
        },
        {
            "key": "step_04",
            "action": "Lower the tools through the top openings. " + tool["check"] if quantity > 1 or tool.get("additional_tools") else "Lower the tool through the top opening. " + tool["check"],
            "add": [],
            "upper_lift_mm": 0,
            "withdraw_mm": 0,
        },
    ]


